export function localizeEmbassy(emb, lang = 'pt') {
  const l = lang === 'en' || lang === 'es' ? lang : 'pt';
  return {
    ...emb,
    paisLocal: emb.pais[l] || emb.pais.pt,
    nomeLocal: emb.nome[l] || emb.nome.pt,
    regiaoLocal: (REGION_LABELS[emb.regiao] && REGION_LABELS[emb.regiao][l]) || emb.regiao,
    horarioLocal: emb.horario_funcionamento[l] || emb.horario_funcionamento.pt,
    observacoesLocal: emb.observacoes_turista[l] || emb.observacoes_turista.pt,
  };
}

export function getGoogleMapsCoordsUrl(latitude, longitude) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${latitude},${longitude}`)}`;
}

export function sanitizeTelHref(phone) {
  return `tel:${String(phone || '').replace(/[^\d+]/g, '')}`;
}
